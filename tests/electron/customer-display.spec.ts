import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { _electron as electron, expect, test } from '@playwright/test';
import { navigateTo } from './navigation-helpers.js';

test('saved colors edit/delete and a separate read-only customer cart stays live across payment and restart', async () => {
  test.setTimeout(120_000);
  const directory = await mkdtemp(join(tmpdir(), 'sloth-customer-colors-'));
  const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ args: [resolve('apps/desktop')], env: { ...environment, CASH_SLOTH_CHANNEL: 'development', CASH_SLOTH_DATA_ROOT: directory } });
  let app = await launch();
  try {
    let page = await app.firstWindow(); await navigateTo(page, 'Settings');
    await page.getByLabel('Custom color', { exact: true }).fill('#123456');
    await page.getByLabel('Color name', { exact: true }).fill('Forest');
    await page.getByRole('button', { name: 'Save color', exact: true }).click();
    await page.getByRole('button', { name: 'Edit color Forest', exact: true }).click();
    await page.getByLabel('Saved color name', { exact: true }).fill('Night sky');
    await page.getByLabel('Saved color value', { exact: true }).fill('#0022cc');
    await page.getByRole('button', { name: 'Save color changes', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Night sky', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Forest', exact: true })).toHaveCount(0);
    await expect(page.getByLabel('Custom color', { exact: true })).toHaveValue('#0022cc');
    await page.getByLabel('Color name', { exact: true }).fill('Spare');
    await page.getByRole('button', { name: 'Save color', exact: true }).click();
    await page.getByRole('button', { name: 'Edit color Night sky', exact: true }).click();
    await page.getByLabel('Saved color name', { exact: true }).fill('Spare');
    await expect(page.getByRole('button', { name: 'Save color changes', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Delete color Spare', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Spare', exact: true })).toHaveCount(0);
    const newWindow = app.waitForEvent('window');
    await page.getByRole('button', { name: 'Open customer display', exact: true }).click();
    let customer = await newWindow;
    const firstRead = await customer.evaluate(async () => { try { return { methods: Object.keys(window.cashSlothCustomer ?? {}), result: await window.cashSlothCustomer?.getState({}) }; } catch (error) { return { error: String(error) }; } });
    expect(firstRead).toMatchObject({ methods: ['getState'], result: { ok: true } });
    await expect(customer.getByText('Your items will appear here.', { exact: true })).toBeVisible();
    expect(await customer.evaluate(() => ({ cashier: typeof window.cashSloth, customerMethods: Object.keys(window.cashSlothCustomer ?? {}), node: typeof (window as unknown as { require?: unknown }).require }))).toEqual({ cashier: 'undefined', customerMethods: ['getState'], node: 'undefined' });
    await page.getByRole('button', { name: 'Open customer display', exact: true }).click();
    expect(app.windows()).toHaveLength(2);
    expect(await app.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().includes('?customer=1'))!; window.setBounds({ x: 150, y: 100, width: 1024, height: 768 }); return window.isMovable(); })).toBe(true);
    await navigateTo(page, 'POS');
    await page.getByRole('button', { name: 'Add Chocolate', exact: true }).click();
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 2.47');
    await page.getByRole('button', { name: 'Add Chocolate', exact: true }).click();
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 4.94');
    await expect(customer.locator('.customer-items')).toContainText('CHF 2.47 each');
    await expect(customer.locator('.customer-quantity strong')).toHaveText('2×');
    await page.getByRole('button', { name: 'Checkout', exact: true }).click();
    await page.getByRole('button', { name: 'Cash', exact: true }).click();
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 4.95');
    await page.getByRole('button', { name: 'Add cash CHF 10.00', exact: true }).click();
    await page.getByRole('button', { name: 'Round up to next CHF 5', exact: false }).click();
    await expect(customer.getByTestId('customer-tip')).toHaveText('CHF 0.05');
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 5.00');
    await expect(customer.getByTestId('customer-change')).toHaveText('CHF 5.00');
    for (const width of [1920, 960]) {
      await app.evaluate(({ BrowserWindow }, size) => { BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().includes('?customer=1'))!.setBounds({ width: size, height: size === 1920 ? 1080 : 640 }); }, width);
      await expect.poll(() => customer.evaluate(() => Math.abs(document.querySelector('main')!.getBoundingClientRect().width - document.documentElement.clientWidth))).toBeLessThan(2);
      const layout = await customer.getByTestId('customer-total').evaluate((element) => {
        const range = document.createRange(); range.selectNodeContents(element);
        return { lines: range.getClientRects().length, overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth };
      });
      expect(layout).toEqual({ lines: 1, overflow: false });
      await customer.screenshot({ path: 'test-results/customer-display-' + width + '.png', fullPage: true, animations: 'disabled' });
    }
    await page.getByRole('button', { name: 'Complete transaction', exact: true }).click();
    await expect(customer.getByText('Your items will appear here.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Do not print', exact: true }).click();
    await page.getByRole('button', { name: 'Add Coffee', exact: true }).click();
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 4.50');
    await navigateTo(page, 'Settings');
    await page.getByLabel('Language', { exact: true }).selectOption('de');
    await expect(customer.getByRole('heading', { name: 'Dein Warenkorb', exact: true })).toBeVisible();
    await expect(customer.locator('.customer-item-description > span')).toHaveText('CHF 4.50 pro Stück');
    await page.getByLabel('Sprache', { exact: true }).selectOption('en');
    await customer.close();
    const reopened = app.waitForEvent('window');
    await page.getByRole('button', { name: 'Open customer display', exact: true }).click(); customer = await reopened;
    await expect(customer.getByTestId('customer-total')).toHaveText('CHF 4.50');
    await app.close(); app = await launch(); page = await app.firstWindow();
    expect(app.windows()).toHaveLength(1);
    await navigateTo(page, 'Settings');
    await expect(page.getByRole('button', { name: 'Night sky', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Spare', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Delete color Night sky', exact: true }).click();
    await expect(page.locator('.saved-color-row')).toHaveCount(0);
    await expect(page.getByLabel('Custom color', { exact: true })).toHaveValue('#0022cc');
    const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('cash-sloth.preferences.v1') ?? '{}') as { savedColors: unknown[] });
    expect(stored.savedColors).toEqual([]);
    await navigateTo(page, 'POS'); await expect(page.locator('.pos-event-logo')).toHaveCount(0);
  } finally { await app.close(); await rm(directory, { recursive: true, force: true, maxRetries: 5 }); }
});
