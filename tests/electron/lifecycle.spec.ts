import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { _electron as electron, expect, test } from '@playwright/test';
import { navigateTo } from './navigation-helpers.js';

test('new events are empty, presets copy independently and catalog entries and presets can be deleted', async () => {
  test.setTimeout(90_000);
  const directory = await mkdtemp(join(tmpdir(), 'sloth-lifecycle-'));
  const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ args: [resolve('apps/desktop')], env: { ...environment, CASH_SLOTH_CHANNEL: 'development', CASH_SLOTH_DATA_ROOT: directory } });
  let app = await launch();
  try {
    let page = await app.firstWindow(); await navigateTo(page, 'Presets');
    await page.getByLabel('New event name', { exact: true }).fill('Original event');
    await page.getByRole('button', { name: 'Create empty preset', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Original event');
    await navigateTo(page, 'Catalog');
    await expect(page.locator('.editor-product-list button')).toHaveCount(0);
    await expect(page.locator('.category-row')).toHaveCount(0);
    await page.getByRole('button', { name: 'New product', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Save product', exact: true })).toBeDisabled();
    await expect(page.getByRole('status').filter({ hasText: 'Create an active category first' })).toBeVisible();
    await page.getByRole('button', { name: 'Cancel product', exact: true }).click();
    await page.getByRole('button', { name: 'New category', exact: true }).click();
    await page.getByLabel('Category name', { exact: true }).fill('Food');
    await page.getByRole('button', { name: 'Save category', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('button', { name: 'Edit category Food', exact: true }).click();
    const categoryDialog = page.getByRole('dialog', { name: 'Edit category', exact: true });
    const sizes = await categoryDialog.locator('button').filter({ hasText: /Save category|Cancel category|Delete category|Reload saved category/ }).evaluateAll((buttons) => buttons.map((button) => ({ width: button.getBoundingClientRect().width, height: button.getBoundingClientRect().height })));
    expect(sizes).toHaveLength(4);
    for (const size of sizes) { expect(size.width).toBeCloseTo(sizes[0]!.width, 0); expect(size.height).toBeCloseTo(sizes[0]!.height, 0); }
    await page.screenshot({ path: 'test-results/category-equal-buttons.png', animations: 'disabled' });
    await categoryDialog.getByRole('button', { name: 'Cancel category', exact: true }).click();
    await page.getByRole('button', { name: 'New product', exact: true }).click();
    await page.getByLabel('Product name', { exact: true }).fill('Döner');
    await page.getByLabel('Product category', { exact: true }).selectOption({ label: 'Food' });
    await page.getByLabel('Price (CHF)', { exact: true }).fill('12.00');
    await page.getByRole('button', { name: 'Add another variant', exact: true }).click();
    const second = page.locator('.draft-variant').nth(1);
    await second.getByLabel('Variant name', { exact: true }).fill('Box');
    await second.getByLabel('Price (CHF)', { exact: true }).fill('14.00');
    await page.screenshot({ path: 'test-results/create-multiple-variants.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Save product', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Edit product Döner', exact: true })).toBeVisible();
    await expect(page.locator('.managed-variant')).toHaveCount(2);
    await page.getByRole('button', { name: 'Delete variant Box', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await expect(page.locator('.managed-variant')).toHaveCount(1);
    await expect(page.getByRole('button', { name: 'Delete variant Default', exact: true })).toBeDisabled();
    await page.getByRole('checkbox', { name: 'Assign Food', exact: true }).check();
    await page.getByRole('button', { name: 'Save categories', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Changes saved on this device.' })).toBeVisible();
    await navigateTo(page, 'Presets');
    await page.getByRole('button', { name: 'Save changes to active preset', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Preset saved and active.');
    await page.getByRole('button', { name: 'Copy preset Original event', exact: true }).click();
    const copy = page.getByRole('dialog', { name: 'Copy preset', exact: true });
    await copy.getByLabel('New event name', { exact: true }).fill('Similar event');
    await copy.getByRole('button', { name: 'Create copy', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Similar event');
    await navigateTo(page, 'Catalog'); await page.getByRole('button', { name: 'Edit product Döner', exact: true }).click();
    await page.getByLabel('Product name', { exact: true }).fill('Döner spezial');
    await page.getByRole('button', { name: 'Save product', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Edit product Döner spezial', exact: true })).toBeVisible();
    await navigateTo(page, 'Presets'); await page.getByRole('button', { name: 'Save changes to active preset', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Preset saved and active.');
    await page.getByRole('button', { name: 'Load preset Original event', exact: true }).click(); await page.getByRole('button', { name: 'Confirm load preset', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Original event');
    await navigateTo(page, 'POS'); await expect(page.getByRole('button', { name: 'Add Döner', exact: true })).toBeVisible();
    await navigateTo(page, 'Presets'); await page.getByRole('button', { name: 'Load preset Similar event', exact: true }).click(); await page.getByRole('button', { name: 'Confirm load preset', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Similar event');
    await page.screenshot({ path: 'test-results/preset-copy-delete.png', fullPage: true, animations: 'disabled' });
    await navigateTo(page, 'Catalog'); await page.getByRole('button', { name: 'Edit product Döner spezial', exact: true }).click();
    await page.getByRole('button', { name: 'Delete product', exact: true }).click(); await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await expect(page.locator('.editor-product-list button')).toHaveCount(0);
    await page.getByRole('button', { name: 'Edit category Food', exact: true }).click();
    await page.getByRole('button', { name: 'Delete category', exact: true }).click(); await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await expect(page.locator('.category-row')).toHaveCount(0);
    await navigateTo(page, 'Presets'); await page.getByRole('button', { name: 'Save changes to active preset', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Preset saved and active.');
    await page.getByRole('button', { name: 'Delete preset Original event', exact: true }).click(); await page.getByRole('button', { name: 'Confirm delete preset', exact: true }).click();
    await expect(page.locator('.preset-row')).toHaveCount(1);
    await page.getByRole('button', { name: 'Delete preset Similar event', exact: true }).click(); await page.getByRole('button', { name: 'Confirm delete preset', exact: true }).click();
    await expect(page.locator('.preset-row')).toHaveCount(0);
    await app.close(); app = await launch(); page = await app.firstWindow(); await navigateTo(page, 'Catalog');
    await expect(page.locator('.editor-product-list button')).toHaveCount(0);
    await expect(page.locator('.category-row')).toHaveCount(0);
    await navigateTo(page, 'Presets'); await expect(page.locator('.preset-row')).toHaveCount(0);
  } finally { await app.close(); await rm(directory, { recursive: true, force: true, maxRetries: 5 }); }
});
