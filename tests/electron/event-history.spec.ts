import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { _electron as electron, expect, test } from '@playwright/test';
import { navigateTo } from './navigation-helpers.js';

test('event and device histories permanently remove incorrect sales and receipts after restart', async () => {
  test.setTimeout(90_000);
  const directory = await mkdtemp(join(tmpdir(), 'sloth-event-history-'));
  const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ args: [resolve('apps/desktop')], env: { ...environment, CASH_SLOTH_CHANNEL: 'development', CASH_SLOTH_DATA_ROOT: directory } });
  let app = await launch();
  try {
    let page = await app.firstWindow();
    await expect(page.getByRole('button', { name: 'Add Chocolate', exact: true })).toBeVisible();
    await navigateTo(page, 'Presets');
    const seeded = await page.evaluate(async () => {
      const api = window.cashSloth!;
      const value = <T,>(result: { ok: true; value: T } | { ok: false; error: { message: string } }): T => { if (!result.ok) throw new Error(result.error.message); return result.value; };
      const firstState = value(await api.presets.getState({}));
      const created = value(await api.presets.save({ operationId: crypto.randomUUID(), catalogVersion: firstState.catalogVersion, name: 'Summer event', presetId: null, expectedRevision: null, empty: false }));
      const a = created.active!.id;
      const sell = async () => {
        let cart = value(await api.pos.getCart({})).cart;
        cart = value(await api.pos.addItem({ cartId: cart.id, expectedRevision: cart.revision, variantId: 'variant-chocolate-default' }));
        const checkout = value(await api.payments.startCheckout({ cartId: cart.id, expectedRevision: cart.revision }));
        const attempt = value(await api.payments.preparePayment({ sessionId: checkout.session.id, idempotencyKey: crypto.randomUUID(), method: 'card', intendedRappen: 247 }));
        value(await api.payments.confirmPayment({ attemptId: attempt.id, operatorConfirmed: true }));
        return value(await api.payments.completeCheckout({ sessionId: checkout.session.id }));
      };
      const saleA = await sell();
      const state = value(await api.presets.getState({}));
      const copied = value(await api.presets.copy({ operationId: crypto.randomUUID(), catalogVersion: state.catalogVersion, presetId: a, expectedRevision: state.presets.find((p) => p.id === a)!.revision, name: 'Winter event' }));
      const saleB = await sell();
      return { a, b: copied.active!.id, saleA: saleA.id, saleB: saleB.id };
    });
    await navigateTo(page, 'Sales history');
    await expect(page.getByRole('button', { name: 'Event history', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(page.getByLabel('History event', { exact: true })).toHaveValue(seeded.b);
    await expect(page.locator('.history-sale-entry')).toHaveCount(1);
    await expect(page.locator('.history-sale-entry')).toContainText('Winter event');
    await page.getByRole('button', { name: 'Open sale ' + seeded.saleB, exact: true }).click();
    await page.getByRole('button', { name: 'View / print receipt', exact: true }).click();
    await expect(page.locator('.receipt-paper header strong')).toHaveText('Winter event');
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await navigateTo(page, 'Sales history');
    await page.getByRole('button', { name: 'Delete sale ' + seeded.saleB, exact: true }).click();
    const deletion = page.getByRole('dialog', { name: 'Delete sale?', exact: true });
    await expect(deletion.getByRole('button', { name: 'Confirm delete sale', exact: true })).toBeDisabled();
    await deletion.getByLabel('Reason for deletion', { exact: true }).fill('Wrong product selected');
    await deletion.getByRole('button', { name: 'Confirm delete sale', exact: true }).click();
    await expect(deletion).toHaveCount(0); await expect(page.locator('.history-sale-entry')).toHaveCount(0);
    await navigateTo(page, 'POS');
    await expect(page.getByRole('button', { name: 'Add Chocolate', exact: true })).toBeEnabled();
    await expect(page.getByRole('button', { name: 'View / print receipt', exact: true })).toHaveCount(0);
    await navigateTo(page, 'Sales history');
    await page.getByLabel('History event', { exact: true }).selectOption(seeded.a);
    await expect(page.locator('.history-sale-entry')).toHaveCount(1);
    await expect(page.locator('.history-sale-entry')).toContainText('Summer event');
    await page.getByRole('button', { name: 'Device history', exact: true }).click();
    await expect(page.locator('.history-sale-entry')).toHaveCount(1);
    await page.getByRole('checkbox', { name: 'Show deleted sales', exact: true }).check();
    await expect(page.locator('.history-sale-entry')).toHaveCount(1);
    const deleted = await page.evaluate(async (saleId) => window.cashSloth!.payments.getSaleDetails({ saleId }), seeded.saleB);
    expect(deleted).toMatchObject({ ok: false, error: { code: 'NOT_FOUND' } });
    await page.getByRole('button', { name: 'Open sale ' + seeded.saleA, exact: true }).click();
    await page.getByRole('button', { name: 'View / print receipt', exact: true }).click();
    await expect(page.locator('.receipt-paper header strong')).toHaveText('Summer event');
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await app.close(); app = await launch(); page = await app.firstWindow();
    await navigateTo(page, 'Sales history');
    await expect(page.getByLabel('History event', { exact: true })).toHaveValue(seeded.b);
    await expect(page.locator('.history-sale-entry')).toHaveCount(0);
    await page.getByRole('button', { name: 'Device history', exact: true }).click();
    await page.getByRole('checkbox', { name: 'Show deleted sales', exact: true }).check();
    await expect(page.locator('.history-sale-entry')).toHaveCount(1);
    await page.getByRole('button', { name: 'Event history', exact: true }).click();
    await page.getByLabel('History event', { exact: true }).selectOption(seeded.a);
    await page.getByLabel('Product or variant', { exact: true }).fill('No matching product');
    await page.getByRole('button', { name: 'Apply history filters', exact: true }).click();
    await expect(page.locator('.history-sale-entry')).toHaveCount(0);
    await page.getByRole('button', { name: 'Clear event history', exact: true }).click();
    let clear = page.getByRole('dialog', { name: 'Clear event history?', exact: true });
    await expect(clear).toContainText('Summer event'); await expect(clear).toContainText('1 sale');
    await expect(clear.getByRole('button', { name: 'Permanently clear history', exact: true })).toBeDisabled();
    await clear.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Clear event history', exact: true }).click();
    await clear.getByLabel('Reason for deletion', { exact: true }).fill('Clear summer event');
    await clear.getByRole('checkbox', { name: 'I confirm permanent deletion of this entire history.', exact: true }).check();
    await clear.getByRole('button', { name: 'Permanently clear history', exact: true }).click();
    await expect(clear).toHaveCount(0);
    const removedA = await page.evaluate(async (saleId) => window.cashSloth!.payments.getSaleDetails({ saleId }), seeded.saleA);
    expect(removedA.ok).toBe(false);
    await page.evaluate(async () => {
      const api = window.cashSloth!;
      const value = <T,>(result: { ok: true; value: T } | { ok: false; error: { message: string } }): T => { if (!result.ok) throw new Error(result.error.message); return result.value; };
      let cart = value(await api.pos.getCart({})).cart;
      cart = value(await api.pos.addItem({ cartId: cart.id, expectedRevision: cart.revision, variantId: 'variant-chocolate-default' }));
      const checkout = value(await api.payments.startCheckout({ cartId: cart.id, expectedRevision: cart.revision }));
      const attempt = value(await api.payments.preparePayment({ sessionId: checkout.session.id, idempotencyKey: crypto.randomUUID(), method: 'card', intendedRappen: 247 }));
      value(await api.payments.confirmPayment({ attemptId: attempt.id, operatorConfirmed: true })); value(await api.payments.completeCheckout({ sessionId: checkout.session.id }));
    });
    await page.getByRole('button', { name: 'Device history', exact: true }).click();
    await page.getByRole('button', { name: 'Clear entire device history', exact: true }).click();
    clear = page.getByRole('dialog', { name: 'Clear entire device history?', exact: true });
    await expect(clear).toContainText('1 sale');
    await clear.getByLabel('Reason for deletion', { exact: true }).fill('Reset device history');
    await clear.getByRole('checkbox', { name: 'I confirm permanent deletion of this entire history.', exact: true }).check();
    await page.screenshot({ path: 'test-results/clear-device-history.png', animations: 'disabled' });
    await clear.getByRole('button', { name: 'Permanently clear history', exact: true }).click();
    await expect(clear).toHaveCount(0);
    await app.close(); app = await launch(); page = await app.firstWindow(); await navigateTo(page, 'Sales history');
    await page.getByRole('button', { name: 'Device history', exact: true }).click();
    await expect(page.locator('.history-sale-entry')).toHaveCount(0);
    const final = await page.evaluate(async () => ({ presets: await window.cashSloth!.presets.getState({}), sales: await window.cashSloth!.payments.listRecentSales({}) }));
    expect(final.sales).toMatchObject({ ok: true, value: [] });
    if (!final.presets.ok) throw new Error(final.presets.error.message); expect(final.presets.value.presets).toHaveLength(2);
  } finally { await app.close(); await rm(directory, { recursive: true, force: true, maxRetries: 5 }); }
});
