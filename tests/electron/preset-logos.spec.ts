import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { _electron as electron, expect, test, type Locator } from '@playwright/test';
import { navigateTo } from './navigation-helpers.js';

test('preset names and individual logos can be created, edited, copied and loaded on both screens', async () => {
  test.setTimeout(120_000);
  const directory = await mkdtemp(join(tmpdir(), 'sloth-preset-logos-'));
  const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ args: [resolve('apps/desktop')], env: { ...environment, CASH_SLOTH_CHANNEL: 'development', CASH_SLOTH_DATA_ROOT: directory } });
  let app = await launch();
  const upload = async (scope: Locator, path: string) => { await scope.getByLabel('Logo image file', { exact: true }).setInputFiles(resolve(path)); await expect(scope.locator('.custom-logo-preview img')).toBeVisible(); };
  try {
    let page = await app.firstWindow(); await navigateTo(page, 'Settings');
    await expect(page.getByRole('button', { name: 'Choose logo', exact: true })).toHaveCount(0);
    const opened = app.waitForEvent('window'); await page.getByRole('button', { name: 'Open customer display', exact: true }).click();
    const customer = await opened;
    await navigateTo(page, 'Presets');
    const create = page.locator('.preset-create-form');
    await create.getByLabel('New event name', { exact: true }).fill('Event A');
    await upload(create, 'apps/pos-ui/src/assets/cash-note-50.png');
    const logoA = await create.locator('.custom-logo-preview img').getAttribute('src');
    await create.getByRole('button', { name: 'Create empty preset', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Event A');
    await expect(customer.getByRole('heading', { name: 'Event A', exact: true })).toBeVisible();
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveAttribute('src', logoA!);
    await navigateTo(page, 'POS'); await expect(page.locator('.pos-event-logo')).toHaveAttribute('src', logoA!);
    await expect(page.locator('.product-card')).toHaveCount(0);
    await navigateTo(page, 'Presets');
    await create.getByLabel('New event name', { exact: true }).fill('Event B');
    await upload(create, 'apps/pos-ui/src/assets/cash-note-200.png');
    const logoB = await create.locator('.custom-logo-preview img').getAttribute('src'); expect(logoB).not.toBe(logoA);
    await create.getByRole('button', { name: 'Create empty preset', exact: true }).click();
    await expect(customer.getByRole('heading', { name: 'Event B', exact: true })).toBeVisible();
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveAttribute('src', logoB!);
    await page.getByRole('button', { name: 'Edit preset Event A', exact: true }).click();
    const edit = page.getByRole('dialog', { name: 'Edit preset', exact: true });
    await edit.getByLabel('Event name', { exact: true }).fill('Event A renamed');
    await upload(edit, 'assets/branding/generated/cash-sloth-128.png');
    const editedLogo = await edit.locator('.custom-logo-preview img').getAttribute('src');
    await edit.getByRole('button', { name: 'Save preset settings', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Event B');
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveAttribute('src', logoB!);
    await page.getByRole('button', { name: 'Load preset Event A renamed', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm load preset', exact: true }).click();
    await expect(customer.getByRole('heading', { name: 'Event A renamed', exact: true })).toBeVisible();
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveAttribute('src', editedLogo!);
    await page.getByRole('button', { name: 'Copy preset Event A renamed', exact: true }).click();
    const copy = page.getByRole('dialog', { name: 'Copy preset', exact: true });
    await copy.getByLabel('New event name', { exact: true }).fill('Event C'); await copy.getByRole('button', { name: 'Create copy', exact: true }).click();
    await expect(customer.getByRole('heading', { name: 'Event C', exact: true })).toBeVisible();
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveAttribute('src', editedLogo!);
    await page.getByRole('button', { name: 'Edit preset Event C', exact: true }).click();
    await edit.getByLabel('Event name', { exact: true }).fill('Event C renamed');
    await edit.getByRole('button', { name: 'Remove logo', exact: true }).click();
    await edit.getByRole('button', { name: 'Save preset settings', exact: true }).click();
    await expect(customer.getByRole('heading', { name: 'Event C renamed', exact: true })).toBeVisible();
    await expect(customer.getByAltText('Custom logo', { exact: true })).toHaveCount(0);
    await navigateTo(page, 'POS'); await expect(page.locator('.pos-event-logo')).toHaveCount(0);
    await navigateTo(page, 'Presets');
    await page.getByRole('button', { name: 'Load preset Event A renamed', exact: true }).click(); await page.getByRole('button', { name: 'Confirm load preset', exact: true }).click();
    await expect(page.getByLabel('Event name', { exact: true })).toHaveValue('Event A renamed');
    await app.close(); app = await launch(); page = await app.firstWindow();
    await expect(page.getByRole('heading', { name: 'Event A renamed', exact: true })).toBeVisible();
    await expect(page.locator('.pos-event-logo')).toHaveAttribute('src', editedLogo!);
    await navigateTo(page, 'Presets');
    await page.getByRole('button', { name: 'Edit preset Event A renamed', exact: true }).click();
    await page.screenshot({ path: 'test-results/preset-logo-editor.png', fullPage: true, animations: 'disabled' });
    const restored = page.getByRole('dialog', { name: 'Edit preset', exact: true });
    await expect(restored.locator('.custom-logo-preview img')).toHaveAttribute('src', editedLogo!);
    await restored.getByLabel('Logo image file', { exact: true }).setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
    await expect(restored.getByRole('alert')).toContainText('PNG, JPG or WebP');
    await expect(restored.locator('.custom-logo-preview img')).toHaveAttribute('src', editedLogo!);
  } finally { await app.close(); await rm(directory, { recursive: true, force: true, maxRetries: 5 }); }
});
